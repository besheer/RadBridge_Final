#!/usr/bin/env python3
"""Generate a lightweight source-code inventory for developer handover.

This is intentionally static-analysis only: importing app.py could connect to services,
create directories, or require runtime configuration. The generator parses Python AST.
"""
from __future__ import annotations
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from web.source_contract import app_source
APP = ROOT / "app.py"
OUT = ROOT / "docs" / "CODE_MAP.md"

def deco_name(node):
    try:
        return ast.unparse(node)
    except Exception:
        return "<decorator>"

def main():
    tree = ast.parse(app_source(), filename=str(APP))
    ownership = json.loads((ROOT / 'application/component_manifest.json').read_text(encoding='utf-8'))
    locations = {}
    for module in {entry['module'] for entry in ownership}:
        relative = module.replace('.', '/') + '.py'
        owned_tree = ast.parse((ROOT / relative).read_text(encoding='utf-8'))
        installers = {node.name: node for node in owned_tree.body if isinstance(node, ast.FunctionDef)}
        for entry in (item for item in ownership if item['module'] == module):
            handler = next(node for node in installers[entry['installer']].body if isinstance(node, ast.FunctionDef) and node.name == entry['symbol'])
            locations[entry['symbol']] = f'[{relative}:{handler.lineno}](../{relative}#L{handler.lineno})'
    models=[]; routes=[]; functions=[]
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            bases=[ast.unparse(b) for b in node.bases]
            if any('db.Model' in b for b in bases):
                models.append((node.name,node.lineno))
        elif isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef)):
            route_decos=[]
            for d in node.decorator_list:
                s=deco_name(d)
                if s.startswith('app.route(') or s.startswith('app.get(') or s.startswith('app.post(') or s.startswith('app.put(') or s.startswith('app.delete('):
                    route_decos.append(s)
            if route_decos:
                routes.append((node.name,locations[node.name],route_decos))
            functions.append((node.name,locations[node.name]))
    for path in sorted((ROOT / 'infrastructure/models').glob('*.py')):
        schema = ast.parse(path.read_text(encoding='utf-8'))
        for node in schema.body:
            name = None
            if isinstance(node, ast.ClassDef) and any(ast.unparse(base) == 'db.Model' for base in node.bases):
                name = node.name
            elif isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name) and node.value.func.id == 'type':
                if node.value.args and isinstance(node.value.args[0], ast.Constant):
                    name = node.value.args[0].value
            if name:
                relative = path.relative_to(ROOT).as_posix()
                models.append((name, f'[{relative}:{node.lineno}](../{relative}#L{node.lineno})'))
    lines=[
        '# Generated Code Map','',
        '> Generated by `python tools/generate_code_map.py`. Do not hand-edit this file; regenerate it after structural changes.','',
        f'- Canonical ORM models: **{len(models)}**', f'- Composed root route functions: **{len(routes)}**', f'- Owned composed functions: **{len(functions)}**','',
        'Additional extension routes and services are mapped by `application/module_manifest.json`; route-function counts differ from URL registrations.','',
        '## ORM Models','', '| Model | Executable source |','|---|---|'
    ]
    lines += [f'| `{n}` | {ln} |' for n,ln in models]
    lines += ['', '## Composed Routes','', '| Function | Decorator(s) | Executable source |','|---|---|---|']
    for n,ln,decos in routes:
        esc='<br>'.join('`'+d.replace('|','\\|')+'`' for d in decos)
        lines.append(f'| `{n}` | {esc} | {ln} |')
    lines += ['', '## Key Worker / Module Files','',
              '- `workers/pacs_worker.py` — PACS intake and queued transfer worker.',
              '- `workers/backup_worker.py` — scheduled DB/files/cloud backup worker.',
              '- `domain/clinical/workflow.py` — clinical workflow state transition rules.',
              '- `application/services/registration/procedure_catalog.py` — procedure catalog data/helpers.',
              '- `web/factory.py` — explicit independent clinical composition and lifecycle.',
              '', '## Regeneration','', '```bash','python tools/generate_code_map.py','```','']
    OUT.write_text('\n'.join(lines),encoding='utf-8')
    print(f'Wrote {OUT} ({len(models)} models, {len(routes)} route functions)')
if __name__=='__main__': main()
